function define(faction: Faction, rows: PartRow[]) {
  for (const r of rows) {
    const [
      id,
      name,
      kind,
      tags,
      layout,
      w,
      h,
      cd,
      value,
      load,
      price,
      desc,
      extra = {},
    ] = r;
    PARTS[id] = {
      id,
      name,
      faction,
      kind,
      tags: tags.split(" "),
      layout,
      w,
      h,
      cd,
      value,
      load,
      price,
      desc,
      added: !!extra.added,
      minW: Math.min(
        w,
        layout === "button" ? 72 : layout === "link" ? 80 : 140,
      ),
      minH: Math.min(h, 28),
      maxW: 920,
      maxH: 500,
      ...extra,
    };
  }
}
